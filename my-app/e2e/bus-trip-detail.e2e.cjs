const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const M = require('../../backend/src/transport/models');
const S = require('../../backend/src/transport/service');
const { User } = require('../../backend/src/models');
const jwt = require('../../backend/node_modules/jsonwebtoken');
const { JWT_SECRET } = require('../../backend/src/middlewares/auth.middleware');

(async () => {
 const uid = `bus-detail-check-${Date.now()}`;
 const artifacts = path.resolve(__dirname, '../../tmp/bus-detail');
 fs.mkdirSync(artifacts, { recursive: true });
 let browser, userCreated = false;
 try {
  await M.store.authenticate();
  const route = await M.col('routes').findOne({origin:'Đà Nẵng',destination:'Hội An'});
  const trip = await M.col('trips').findOne({route_id:route._id,transport_type:'bus',departure_time:{$gt:new Date()},available_seats:{$gte:2},status:'active','stops.3':{$exists:true}});
  assert.ok(trip, 'A future seeded multi-stop bus trip is required');
  const user = {id:uid,username:uid,fullname:'Bus detail verification',email:`${uid}@greensteps.invalid`,role:'traveler'};
  await User.create({...user,password_hash:'disabled-test-account'}); userCreated = true;
  const token = jwt.sign({id:uid,role:'traveler'},JWT_SECRET,{expiresIn:'15m'});
  browser = await chromium.launch({headless:true,channel:'chrome'});
  const page = await browser.newPage({viewport:{width:1536,height:1024}});
  const errors = [];
  page.on('pageerror',e=>errors.push(e.message));
  await page.addInitScript(({user,token})=>{localStorage.setItem('greensteps_user',JSON.stringify(user));localStorage.setItem('greensteps_token',token);},{user,token});
  const url = `http://127.0.0.1:4200/transport/trips/${trip._id}?type=bus`;
  await page.goto('http://127.0.0.1:4200/transport?type=bus&passengers=1&sortBy=departure');
  await page.locator('.transport-card').first().waitFor();
  assert.equal(await page.locator('.notice.error').count(),0);
  assert.ok(await page.locator('.transport-card').count()>0);
  await page.goto(url); await page.waitForLoadState('networkidle');
  await page.locator('.bus-heading h1').waitFor();
  assert.match(await page.locator('.bus-heading h1').innerText(),/Đà Nẵng → Hội An/);
  assert.equal(await page.locator('.bus-gallery button').count(),3);
  assert.equal(await page.locator('.stop-timeline li').count(),4);
  assert.equal(await page.locator('.bus-continue').isDisabled(),true);
  assert.ok(await page.locator('.bus-gallery img').evaluateAll(imgs=>imgs.every(i=>i.complete&&i.naturalWidth>0&&i.src.startsWith('data:image/jpeg;base64,'))));
  const ids=trip.stops.map(s=>s.id);
  await page.selectOption('#bus-pickup',ids[1]);
  assert.equal(await page.locator('#bus-dropoff option:not([disabled])').count(),2);
  assert.match(await page.locator('.selected-duration').innerText(),/45 phút/);
  assert.equal(await page.locator('.selected-line').count(),2);
  await page.selectOption('#bus-dropoff',ids[2]);
  await page.locator('input[name=busTerms]').check();
  await page.selectOption('#bus-pickup',ids[2]);
  await page.waitForFunction(()=>document.querySelector('#bus-dropoff')?.value === '' && document.querySelector('input[name=busTerms]')?.checked === false);
  assert.equal(await page.inputValue('#bus-dropoff'),'');
  assert.equal(await page.locator('input[name=busTerms]').isChecked(),false);
  assert.equal(await page.locator('.bus-continue').isDisabled(),true);
  await page.selectOption('#bus-pickup',ids[1]);
  await page.selectOption('#bus-dropoff',ids[3]);
  await page.locator('.bus-gallery button').nth(2).click();
  assert.equal(await page.locator('dialog').evaluate(d=>d.open),true);
  await page.getByRole('button',{name:'Ảnh tiếp theo',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('.gallery-toolbar')?.textContent.includes('4 / 4'));
  assert.match(await page.locator('.gallery-toolbar').innerText(),/4 \/ 4/);
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('dialog').evaluate(d=>d.open),false);
  await page.screenshot({path:path.join(artifacts,'desktop.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:path.join(artifacts,'mobile.png'),fullPage:true});
  const layout = await page.evaluate(()=>{
   const box=s=>document.querySelector(s).getBoundingClientRect();
   return {overflow:document.documentElement.scrollWidth>innerWidth,route:box('.route-card').bottom,booking:box('.bus-booking').top,bookingEnd:box('.bus-booking').bottom,policies:box('.bus-policies').top};
  });
  assert.equal(layout.overflow,false);assert.ok(layout.booking>=layout.route);assert.ok(layout.policies>=layout.bookingEnd);
  await page.setViewportSize({width:1536,height:1024});
  await page.locator('#bus-seats').fill('999');await page.locator('input[name=busTerms]').check();
  assert.equal(await page.locator('.bus-continue').isDisabled(),true);
  await page.locator('#bus-seats').fill('2');await page.locator('input[name=busTerms]').check();
  await page.locator('.bus-continue').click();
  await page.waitForURL(/\/booking\/payment\?transportBookingId=/);
  await page.locator('.payment-summary .payment-tour-name').waitFor();
  assert.match(await page.locator('.payment-summary').innerText(),/Cầu Rồng/);
  assert.match(await page.locator('.payment-summary').innerText(),/Trung tâm Hội An/);
  const saved=await M.col('bookings').findOne({user_id:uid});
  assert.equal(saved.pickup_stop_id,ids[1]);assert.equal(saved.dropoff_stop_id,ids[3]);assert.equal(saved.total_price,trip.price_per_person*2);
  await page.reload();await page.locator('#acceptedTermsCheck').waitFor();
  assert.equal(await M.col('bookings').countDocuments({user_id:uid}),1);
  await page.locator('#acceptedTermsCheck').check();await page.locator('.payment-continue-desktop').click({force:true});
  await page.waitForURL(/\/booking\/confirm\?transportBookingId=/);
  await page.locator('.confirm-trip-meta').waitFor();
  assert.match(await page.locator('.confirm-trip-meta').innerText(),/Cầu Rồng/);
  await page.goto(`http://127.0.0.1:4200/transport-bookings/${saved._id}`);await page.locator('.transport-bookings article').waitFor();
  assert.match(await page.locator('.transport-bookings article').innerText(),/Cầu Rồng/);
  assert.match(await page.locator('.transport-bookings article').innerText(),/Trung tâm Hội An/);
  // Exercise legacy API payload and a single-image vehicle without mutating Atlas.
  const legacy=await S.detail('trips',String(trip._id));delete legacy.stops;
  legacy.vehicle.images=legacy.vehicle.images.slice(0,1);
  await page.route(`**/api/transport/trips/${trip._id}*`,r=>r.fulfill({json:{success:true,data:legacy}}));
  await page.goto(url);await page.locator('.bus-heading h1').waitFor();
  assert.equal(await page.locator('.stop-timeline li').count(),2);
  assert.equal(await page.locator('.bus-gallery.single-image button').count(),1);
  assert.ok(await page.inputValue('#bus-pickup'));assert.ok(await page.inputValue('#bus-dropoff'));
  const widths=await page.locator('.bus-gallery').evaluate(el=>({gallery:el.clientWidth,image:el.querySelector('button').clientWidth}));
  assert.equal(widths.gallery,widths.image);
  await page.screenshot({path:path.join(artifacts,'legacy-mobile.png'),fullPage:true});
  assert.deepEqual(errors,[]);
  console.log('PASS: Atlas base64 gallery, intermediate pickup, invalidated dropoff, segment duration, modal, mobile order/width, seat/terms gates, checkout/reload/payment/booking snapshots, legacy two stops and one image.');
  console.log(`Screenshots: ${artifacts}`);
 } finally {
  if(browser)await browser.close();
  if(userCreated){
   const bookings=await M.col('bookings').find({user_id:uid}).toArray();
   for(const b of bookings)if(M.active.includes(b.booking_status))await S.changeStatus(String(b._id),{id:uid},'CANCELLED');
   await M.col('bookings').deleteMany({user_id:uid});await User.collection.deleteOne({id:uid});
  }
  await M.store.close();
 }
})().catch(e=>{console.error(e);process.exitCode=1;});
