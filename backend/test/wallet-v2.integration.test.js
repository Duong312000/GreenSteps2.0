const { test } = require('node:test');
const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
require('../src/config/env');
test('wallet API: verified money, points ledger, idempotency, ownership and booking rewards', { skip: !process.env.TEST_MONGODB_URI, timeout: 60000 }, async () => {
  const uri = new URL(process.env.TEST_MONGODB_URI);
  uri.pathname = `/WalletTest_${randomUUID().replaceAll('-', '')}`;
  process.env.MONGODB_URI = uri.toString();
  const { store, Wallet, User, ServiceBooking, WalletTransaction, Voucher, GreenService, Vender, CommunityChallengeEntry } = require('../src/models');
  const { earn, earnChallenge } = require('../src/services/wallet.service');
  const jwt = require('jsonwebtoken');
  const { JWT_SECRET } = require('../src/middlewares/auth.middleware');
  let server;
  try {
    await store.sync();
    for (const [id, role] of [['alice', 'traveler'], ['bob', 'traveler'], ['admin', 'admin']]) await User.create({ id, username: id, email: `${id}@example.invalid`, password_hash: 'unused', role });
    const app = require('../src/app'); server = app.listen(0, '127.0.0.1'); await new Promise(r => server.once('listening', r));
    const request = async (path, method = 'GET', body, user = 'alice', key = randomUUID()) => {
      const response = await fetch(`http://127.0.0.1:${server.address().port}/api/wallet${path}`, { method, headers: { 'Content-Type': 'application/json', 'Idempotency-Key': key, ...(user ? { Authorization: `Bearer ${jwt.sign({ id: user, role: user === 'admin' ? 'admin' : 'traveler' }, JWT_SECRET)}` } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}) });
      return { status: response.status, data: await response.json() };
    };
    assert.equal((await request('/overview', 'GET', null, null)).status, 401);
    let overview = (await request('/overview')).data;
    const walletId = overview.wallet.id;
    assert.equal(overview.wallet.balance, 0);
    const depositKey = randomUUID();
    assert.equal((await request('/deposit', 'POST', { amount: -50000 })).status, 400);
    assert.equal((await request('/deposit', 'POST', { amount: 100000 }, 'alice', depositKey)).status, 202);
    await request('/deposit', 'POST', { amount: 100000 }, 'alice', depositKey);
    overview = (await request('/overview')).data;
    assert.equal(overview.transactions.length, 1); assert.equal(overview.wallet.balance, 0);
    const txId = overview.transactions[0].id;
    assert.equal((await request(`/deposits/${txId}/approve`, 'POST', { verificationReference: 'BANK-TEST-001' })).status, 403);
    assert.equal((await request(`/deposits/${txId}/approve`, 'POST', {}, 'admin')).status, 400);
    assert.equal((await request(`/deposits/${txId}/approve`, 'POST', { verificationReference: 'BANK-TEST-001' }, 'admin')).status, 200);
    assert.equal((await request(`/deposits/${txId}/approve`, 'POST', { verificationReference: 'BANK-TEST-001' }, 'admin')).status, 409);
    assert.equal((await request('/overview')).data.wallet.balance, 100000);
    const w = await Wallet.findByPk(walletId); await w.update({ green_points: 3000, tier_points: 5000 });
    const redeemKey = randomUUID();
    const redemption = await request('/points/redeem', 'POST', { points: 1000 }, 'alice', redeemKey);
    assert.equal(redemption.status, 200);
    await request('/points/redeem', 'POST', { points: 1000 }, 'alice', redeemKey);
    assert.equal((await request('/overview')).data.wallet.green_points, 2000);
    assert.equal((await Voucher.findOne({ where: { code: redemption.data.code } })).discount_amount, 1000);
    assert.equal((await request('/points/redeem', 'POST', { points: 999999 })).status, 400);
    const transferKey = randomUUID();
    assert.equal((await request('/points/transfer', 'POST', { email: 'bob@example.invalid', points: 500 }, 'alice', transferKey)).status, 200);
    await request('/points/transfer', 'POST', { email: 'bob@example.invalid', points: 500 }, 'alice', transferKey);
    overview = (await request('/overview')).data;
    assert.equal(overview.wallet.green_points, 1500); assert.equal(overview.membership.points, 5000); assert.equal(overview.membership.name, 'Voyager');
    assert.equal((await request('/overview', 'GET', null, 'bob')).data.wallet.green_points, 500);
    const withdrawal = { amount: 100000, bankName: 'Test bank', bankAccount: '123456789', accountHolder: 'Alice' };
    assert.equal((await request('/withdraw', 'POST', withdrawal)).status, 202);
    assert.equal((await request('/withdraw', 'POST', withdrawal)).status, 400);
    overview = (await request('/overview')).data;
    const wd = overview.transactions.find(t => t.type === 'withdrawal');
    assert.equal(overview.wallet.balance, 100000);
    assert.equal((await request(`/withdrawals/${wd.id}/approve`, 'POST', { verificationReference: 'BANK-PAYOUT-001' }, 'admin')).status, 200);
    assert.equal((await request('/overview')).data.wallet.balance, 0);
    await ServiceBooking.create({ id: 'reward-booking', user_id: 'alice', fullname: 'Alice', name_service: 'Green tour', booking_date: '2026-11-01', guests: 1, value: 1000000, evoucher_code: 'test-voucher', status: 'completed' });
    await store.transaction(async t => { await earn(await ServiceBooking.findByPk('reward-booking', { transaction: t }), t); });
    await store.transaction(async t => { await earn(await ServiceBooking.findByPk('reward-booking', { transaction: t }), t); });
    overview = (await request('/overview')).data;
    assert.equal(overview.wallet.green_points, 1600); assert.equal(overview.membership.points, 5100);
    assert.equal(await WalletTransaction.count({ where: { id: 'points:booking:reward-booking' } }), 1);
    // Failed transaction rolls back both the balance and ledger.
    await assert.rejects(store.transaction(async t => { const wallet = await Wallet.findByPk(walletId, { transaction: t }); await wallet.update({ green_points: 1 }, { transaction: t }); throw new Error('rollback'); }));
    assert.equal((await request('/overview')).data.wallet.green_points, 1600);
    await GreenService.create({ id: 'green-stay', name_service: 'Green stay', type: 'stay', cost: 100000, destination: 'Da Lat', max_capacity: 10 });
    const bookingPayload = { type: 'service', targetId: 'green-stay', bookingDate: '2020-12-01', guests: 1, paymentMethod: 'bank_transfer', voucherCode: redemption.data.code };
    assert.equal((await request('/../bookings', 'POST', bookingPayload, null)).status, 401);
    const booked = await request('/../bookings', 'POST', bookingPayload);
    assert.equal(booked.status, 200); assert.equal(booked.data.payment.amount, 99000);
    assert.equal((await request('/../bookings', 'POST', bookingPayload)).status, 400);
    assert.equal((await request(`/../bookings/${booked.data.bookingId}/complete`, 'POST', {}, 'admin')).status, 409);
    assert.equal((await request(`/../bookings/${booked.data.bookingId}/approve`, 'POST', {}, 'admin')).status, 200);
    assert.equal((await request(`/../bookings/${booked.data.bookingId}/complete`, 'POST', {}, 'admin')).status, 200);
    assert.equal((await request(`/../bookings/${booked.data.bookingId}/complete`, 'POST', {}, 'admin')).status, 200);
    overview = (await request('/overview')).data;
    assert.equal(overview.wallet.green_points, 1609); assert.equal(overview.membership.points, 5109);
    const simultaneous = await Promise.all([request('/points/redeem', 'POST', { points: 1000 }), request('/points/redeem', 'POST', { points: 1000 })]);
    assert.equal(simultaneous.filter(r => r.status === 200).length, 1);
    assert.equal((await request('/overview')).data.wallet.green_points, 609);
    await User.create({ id: 'provider', username: 'provider', email: 'provider@example.invalid', password_hash: 'unused', role: 'provider' });
    await Vender.create({ id: 'green-vender', user_id: 'provider' });
    await GreenService.update({ vender_id: 'green-vender' }, { where: { id: 'green-stay' } });
    await ServiceBooking.create({ id: 'checkin-booking', user_id: 'alice', service_id: 'green-stay', fullname: 'Alice', name_service: 'Green stay', booking_date: '2020-12-01', guests: 1, value: 100000, evoucher_code: 'checkin-evoucher', status: 'deposit', escrow_status: 'holding' });
    assert.equal((await request('/../bookings/checkin', 'POST', { evoucherCode: 'checkin-evoucher' })).status, 403);
    assert.equal((await request('/../bookings/checkin', 'POST', { evoucherCode: 'checkin-evoucher' }, 'admin')).status, 200);
    assert.equal((await request('/../bookings/checkin', 'POST', { evoucherCode: 'checkin-evoucher' }, 'admin')).status, 404);
    assert.equal((await Wallet.findOne({ where: { user_id: 'provider' } })).balance, 90000);
    assert.equal((await request('/overview')).data.wallet.green_points, 619);
    // Reconcile earned legacy points without issuing available points again.
    await User.create({ id: 'legacy', username: 'legacy', email: 'legacy@example.invalid', password_hash: 'unused' });
    await Wallet.create({ id: 'legacy-wallet', user_id: 'legacy', green_points: 100, tier_points: 0 });
    await CommunityChallengeEntry.create({ id: 'old-challenge:legacy', challenge_id: 'old-challenge', user_id: 'legacy', post_id: 'old-post', points: 100 });
    let legacy = (await request('/overview', 'GET', null, 'legacy')).data;
    assert.equal(legacy.wallet.green_points, 100); assert.equal(legacy.membership.points, 100);
    legacy = (await request('/overview', 'GET', null, 'legacy')).data;
    assert.equal(legacy.wallet.green_points, 100); assert.equal(legacy.membership.points, 100);
    assert.equal(legacy.transactions.filter(t => t.type === 'points_tier_adjustment').length, 1);
    const entry = await CommunityChallengeEntry.create({ id: 'new-challenge:legacy', challenge_id: 'new-challenge', user_id: 'legacy', post_id: 'new-post', points: 100 });
    await store.transaction(async t => earnChallenge(entry, t));
    await store.transaction(async t => earnChallenge(entry, t));
    legacy = (await request('/overview', 'GET', null, 'legacy')).data;
    assert.equal(legacy.wallet.green_points, 200); assert.equal(legacy.membership.points, 200);
    await User.create({ id: 'legacy-booking', username: 'legacy-booking', email: 'legacy-booking@example.invalid', password_hash: 'unused' });
    await Wallet.create({ id: 'legacy-booking-wallet', user_id: 'legacy-booking', green_points: 20 });
    await ServiceBooking.create({ id: 'old-completed', user_id: 'legacy-booking', fullname: 'Legacy', name_service: 'Tour', booking_date: '2020-12-01', guests: 1, value: 1000000, evoucher_code: 'old-completed', status: 'completed' });
    const historical = (await request('/overview', 'GET', null, 'legacy-booking')).data;
    assert.equal(historical.wallet.green_points, 20); assert.equal(historical.membership.points, 100);
    assert.equal((await request('/overview', 'GET', null, 'legacy-booking')).data.membership.points, 100);
  } finally { if (server) await new Promise(r => server.close(r)); await store.db.dropDatabase(); await store.close(); }
});
